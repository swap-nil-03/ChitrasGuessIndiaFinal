function romanizeDevanagari(value: string) {
  return [...value].map((char) => DEVANAGARI[char] ?? char).join('');
}
export function normalize(s: string) {
  return romanizeDevanagari(s.toLocaleLowerCase('en-IN')).normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]/gi, '');
}

